def convert(text: str) -> str:
    out = OpenCC('t2s').convert(text)
    for src, dst in VOCAB:
        out = out.replace(src, dst)
    # Mainland typography uses curly quotes rather than corner brackets.
    return out.replace('「', '“').replace('」', '”').replace('『', '‘').replace('』', '’')

